// RED phase (MAC-2n83): the `machinery recover` command battery, written
// against the DESIGNED contract. On unmodified production every test below
// except the fail-closed control fails with cobra's unknown-command error
// instead of the contracted report. The crash fixtures use real subprocess
// death (os.Exit(9)) at meaningful publication boundaries over a real
// filesystem; no in-process simulation stands in for a crash.

