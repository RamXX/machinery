// The sanity run of machinery assess (docs/formats.md section 18.5): the
// real tools on specifications generated from the design alone, with no
// hand-written property. It is kept apart from the manifests and results of
// section 16, which carry hand-written properties and no state counts.

// MachineSanity is what TLC established about one machine.
type MachineSanity struct {
	Machine     string
	Path        string
	States      int      // leaf states of the model
	Distinct    int      // distinct states TLC found
	Unreachable []string // leaves no behavior reaches, in table order
	Deadlock    string   // the first deadlocked leaf TLC reached, or ""
	Error       string   // set when TLC could not check the spec
}

// Failed reports whether the machine has a finding.
func (m MachineSanity) Failed() bool {
	return len(m.Unreachable) > 0 || m.Deadlock != "" || m.Error != ""
}

// ModelSanity is what Alloy established about one model.
type ModelSanity struct {
	Model    string
	Instance bool
	Error    string // set when Alloy could not check the skeleton
}

// SanityTimeout bounds each tool run of the sanity.
const SanityTimeout = 300 * time.Second

var (
	sanityStRe       = regexp.MustCompile(`(?m)^(?:/\\ )?st = "(.*)"\s*$`)
	sanityDistinctRe = regexp.MustCompile(`([0-9]+) distinct states? found`)
	unsafeNameRe     = regexp.MustCompile(`[^A-Za-z0-9_.-]`)
)

func uniq(items []string) []string {
	seen := map[string]bool{}
	var res []string
	for _, s := range items {
		if !seen[s] {
			seen[s] = true
			res = append(res, s)
		}
	}
	return res
}

// sanityLeaves returns the leaves, the initial leaves and the leaves where a
// machine may rest: final leaves and the leaves of states declared _terminal.
func sanityLeaves(m *machine.Machine) (leaves, start, rest []string) {
	t := m.Table
	for _, s := range t.States {
		if s.Kind == "compound" {
			continue
		}
		leaves = append(leaves, s.Path)
		if s.Kind == "final" {
			rest = append(rest, s.Path)
		}
	}
	for _, p := range m.TerminalStates() {
		rest = append(rest, leavesUnder(t, p)...)
	}
	start = []string{m.Resolver.Leaf(t.Initial)}
	for _, e := range t.Entries {
		start = append(start, m.Resolver.Leaf(e))
	}
	return leaves, uniq(start), uniq(rest)
}

// SanityTLA renders the sanity module of a machine (section 18.5).
func SanityTLA(m *machine.Machine) []byte {
	t := m.Table
	leaves, start, rest := sanityLeaves(m)
	var b strings.Builder
	w := func(format string, a ...any) { fmt.Fprintf(&b, format+"\n", a...) }
	w("---- MODULE Sanity ----")
	w("\\* Generated by machinery assess from %s (machine %s). Do not edit.", m.Path, m.ID)
	w("\\* No hand-written property. TLC checks that every state is reachable from the initial")
	w("\\* state or an entry state, and that only final and _terminal states have no next step.")
	w("\\* Guards are not modeled: any branch may fire.")
	w("VARIABLE st")
	w("")
	w("States == %s", tlaSet(leaves))
	w("Start == %s", tlaSet(start))
	w("Rest == %s", tlaSet(rest))
	w("Init == st \\in Start")
	w("")
	steps := []string{}
	for _, tr := range t.Transitions {
		sfx := caseSuffix(tr.ID)
		target := "st"
		if tr.Target != "" {
			target = fmt.Sprintf("%q", m.Resolver.Leaf(tr.Target))
		}
		w("\\* %s", tr.ID)
		w("Step_%s == st \\in %s /\\ st' = %s", sfx, tlaSet(leavesUnder(t, tr.Source)), target)
		steps = append(steps, "Step_"+sfx)
	}
	w("Stay == st \\in Rest /\\ UNCHANGED st")
	steps = append(steps, "Stay")
	w("")
	w("Next ==")
	for _, s := range steps {
		w("    \\/ %s", s)
	}
	w("Spec == Init /\\ [][Next]_st")
	w("====")
	return []byte(b.String())
}

// SanityAlloy renders the file that asks Alloy for an instance of a model's
// skeleton in which every entity exists.
func SanityAlloy(m *design.Model) []byte {
	var sigs []string
	for _, e := range m.Entities {
		if !e.Derived {
			sigs = append(sigs, "some "+AlloyName(e.Name))
		}
	}
	pred := "some univ"
	if len(sigs) > 0 {
		pred = strings.Join(sigs, " and ")
	}
	return []byte(fmt.Sprintf("open %s\n-- Generated by machinery assess. Do not edit.\n-- An instance of the skeleton in which every entity exists.\npred Inhabited { %s }\nrun Inhabited for 4\n", AlloyModule(m.Path), pred))
}

// Sanity runs the sanity of every machine and every model below dir, with
// up to workers TLC runs at once. It returns a ToolError when a tool the
// design needs is missing.
func Sanity(p *project.Project, d *design.Design, dir string, workers int) ([]MachineSanity, []ModelSanity, error) {
	if len(d.Machines) > 0 {
		if err := Ready(p, TLATool); err != nil {
			return nil, nil, err
		}
	}
	if len(d.Models) > 0 {
		if err := Ready(p, AlloyTool); err != nil {
			return nil, nil, err
		}
	}
	if workers < 1 {
		workers = 1
	}
	tlc := &tlcRunner{java: p.Cfg.Tools.Java, jar: TLATool.Path(p.ToolsDir()), workers: 1}
	ms := make([]MachineSanity, len(d.Machines))
	errs := make([]error, len(d.Machines))
	sem := make(chan struct{}, workers)
	var wg sync.WaitGroup
	for i, m := range d.Machines {
		wg.Add(1)
		go func(i int, m *machine.Machine) {
			defer wg.Done()
			sem <- struct{}{}
			defer func() { <-sem }()
			mdir := filepath.Join(dir, "machines", unsafeNameRe.ReplaceAllString(m.ID, "_"))
			ms[i], errs[i] = sanityMachine(tlc, mdir, m)
		}(i, m)
	}
	wg.Wait()
	for _, err := range errs {
		if err != nil {
			return nil, nil, err
		}
	}
	alloy := &alloyRunner{java: p.Cfg.Tools.Java, jar: AlloyTool.Path(p.ToolsDir())}
	var mods []ModelSanity
	used := map[string]int{}
	for _, m := range d.Models {
		name := unsafeNameRe.ReplaceAllString(AlloyModule(m.Path), "_")
		used[name]++
		if used[name] > 1 {
			name = fmt.Sprintf("%s-%d", name, used[name])
		}
		res, err := sanityModel(alloy, filepath.Join(dir, "models", name), m)
		if err != nil {
			return nil, nil, err
		}
		mods = append(mods, res)
	}
	return ms, mods, nil
}

func sanityMachine(tlc *tlcRunner, dir string, m *machine.Machine) (MachineSanity, error) {
	leaves, _, _ := sanityLeaves(m)
	res := MachineSanity{Machine: m.ID, Path: m.Path, States: len(leaves)}
	if len(leaves) == 0 {
		res.Error = "the machine has no states"
		return res, nil
	}
	if err := os.MkdirAll(dir, 0o755); err != nil {
		return res, err
	}
	if err := os.WriteFile(filepath.Join(dir, "Sanity.tla"), SanityTLA(m), 0o644); err != nil {
		return res, err
	}
	if err := os.WriteFile(filepath.Join(dir, "Sanity.cfg"), []byte("SPECIFICATION Spec\n"), 0o644); err != nil {
		return res, err
	}
	dump := []string{"-dump", "states"}
	out, runErr, failure := tlc.exec(dir, "Sanity", "Sanity.cfg", dump, SanityTimeout)
	if failure != "" {
		res.Error = failure
		return res, nil
	}
	o := parseTLC(out, runErr)
	if o.Outcome == "violated" && o.Kind == "deadlock" {
		if sts := sanityStRe.FindAllStringSubmatch(out, -1); len(sts) > 0 {
			res.Deadlock = sts[len(sts)-1][1]
		}
		// TLC stops at the deadlock: explore again for every reachable state
		out, runErr, failure = tlc.exec(dir, "Sanity", "Sanity.cfg", append([]string{"-deadlock"}, dump...), SanityTimeout)
		if failure != "" {
			res.Error = failure
			return res, nil
		}
		o = parseTLC(out, runErr)
	}
	if o.Outcome != "passed" {
		res.Error = o.Violated
		if o.Outcome == "violated" {
			res.Error = "TLC reported " + o.Violated
		}
		return res, nil
	}
	if mm := sanityDistinctRe.FindStringSubmatch(out); mm != nil {
		fmt.Sscanf(mm[1], "%d", &res.Distinct)
	}
	data, err := os.ReadFile(filepath.Join(dir, "states.dump"))
	if err != nil {
		res.Error = "TLC wrote no state dump"
		return res, nil
	}
	reached := map[string]bool{}
	for _, mm := range sanityStRe.FindAllStringSubmatch(string(data), -1) {
		reached[mm[1]] = true
	}
	for _, l := range leaves {
		if !reached[l] {
			res.Unreachable = append(res.Unreachable, l)
		}
	}
	return res, nil
}

func sanityModel(alloy *alloyRunner, dir string, m *design.Model) (ModelSanity, error) {
	res := ModelSanity{Model: m.Path}
	if err := os.MkdirAll(dir, 0o755); err != nil {
		return res, err
	}
	if err := os.WriteFile(filepath.Join(dir, AlloyModule(m.Path)+".als"), AlloySkeleton(m), 0o644); err != nil {
		return res, err
	}
	if err := os.WriteFile(filepath.Join(dir, "Sanity.als"), SanityAlloy(m), 0o644); err != nil {
		return res, err
	}
	found, known, errLine := alloy.exec(dir, "Sanity.als", SanityTimeout)
	switch {
	case errLine != "":
		res.Error = errLine
	case !known["Inhabited"]:
		res.Error = "the run Inhabited was not executed"
	default:
		_, res.Instance = found["Inhabited"]
	}
	return res, nil
}
