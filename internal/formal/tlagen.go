package formal

import (
	"fmt"
	"sort"
	"strings"

	"github.com/RamXX/machinery/internal/machine"
)

func tlaSet(items []string) string {
	q := make([]string, len(items))
	for i, s := range items {
		q[i] = fmt.Sprintf("%q", s)
	}
	return "{" + strings.Join(q, ", ") + "}"
}

func caseSuffix(id string) string {
	s := strings.TrimPrefix(id, "tc:")
	return strings.NewReplacer("-", "_", ".", "_").Replace(s)
}

// leavesUnder lists the leaf states at or below a path, in table order.
func leavesUnder(t *machine.Table, path string) []string {
	var res []string
	for _, s := range t.States {
		if s.Kind == "compound" {
			continue
		}
		if s.Path == path || strings.HasPrefix(s.Path, path+".") {
			res = append(res, s.Path)
		}
	}
	return res
}

// TLASkeleton renders the generated TLA+ module of a machine (section 16.2).
func TLASkeleton(m *machine.Machine) []byte {
	t := m.Table
	var leaves, final, resting []string
	for _, s := range t.States {
		if s.Kind != "compound" {
			leaves = append(leaves, s.Path)
		}
		if s.Kind == "final" && !strings.Contains(s.Path, ".") {
			final = append(final, s.Path)
		}
		if s.Resting {
			resting = append(resting, leavesUnder(t, s.Path)...)
		}
	}
	effSet := map[string]bool{}
	var callerIDs []string
	for _, tr := range t.Transitions {
		for _, e := range tr.Effects {
			effSet[e] = true
		}
		if tr.Kind == "on" {
			callerIDs = append(callerIDs, tr.ID)
		}
	}
	var effects []string
	for e := range effSet {
		effects = append(effects, e)
	}
	sort.Strings(effects)

	var b strings.Builder
	w := func(format string, a ...any) { fmt.Fprintf(&b, format+"\n", a...) }
	w("---- MODULE %s ----", m.Base)
	w("\\* Generated by machinery formal gen from %s. Do not edit.", m.Path)
	w("\\* Properties live in a separate module that EXTENDS this one.")
	w("\\*")
	w("\\* Built-in assumptions of the skeleton:")
	w("\\*   G1  Engine-driven steps (timers, actor results, eventless transitions) are atomic.")
	w("\\*   G2  Guards are not modeled: any branch of a handler may fire.")
	w("\\*   G3  A transition whose source is a compound state applies in each of its leaves.")
	w("EXTENDS Naturals, FiniteSets")
	w("")
	w("CONSTANTS Instances, Callers, Atomic")
	w("")
	w("VARIABLES st, fx, pend, last")
	w("")
	w("vars == <<st, fx, pend, last>>")
	w("")
	w("States == %s", tlaSet(leaves))
	w("Effects == %s", tlaSet(effects))
	w("Final == %s", tlaSet(final))
	w("Resting == %s", tlaSet(resting))
	w("InitialState == %q", m.Resolver.Leaf(t.Initial))
	w("CallerCases == %s", tlaSet(callerIDs))
	w("")
	w("Bump(f, E) == [e \\in Effects |-> IF e \\in E THEN (IF f[e] < 2 THEN f[e] + 1 ELSE 2) ELSE f[e]]")
	w("StepOf(id, i, c, s) == [id |-> id, i |-> i, c |-> c, step |-> s]")
	w("Pending(c, i, id) == [c |-> c, i |-> i, id |-> id]")
	w("InFlight(c) == \\E p \\in pend : p.c = c")
	w("")
	w("TypeOK ==")
	w("    /\\ st \\in [Instances -> States]")
	w("    /\\ fx \\in [Instances -> [Effects -> 0..2]]")
	w("    /\\ pend \\subseteq [c : Callers, i : Instances, id : CallerCases]")
	w("")
	w("Init ==")
	w("    /\\ st = [i \\in Instances |-> InitialState]")
	w("    /\\ fx = [i \\in Instances |-> [e \\in Effects |-> 0]]")
	w("    /\\ pend = {}")
	w("    /\\ last = StepOf(\"init\", \"none\", \"none\", \"init\")")
	w("")
	var caller, internal, commits []string
	for _, tr := range t.Transitions {
		sfx := caseSuffix(tr.ID)
		title := tr.Source + " " + machine.Trigger(tr.Kind, tr.Event)
		if tr.Guard != "" {
			title += " [" + tr.Guard + "]"
		}
		if tr.Target == "" {
			title += " -> (internal)"
		} else {
			title += " -> " + tr.Target
		}
		w("\\* %s  %s", tr.ID, title)
		w("Apply_%s(i) ==", sfx)
		if tr.Target == "" {
			w("    /\\ UNCHANGED st")
		} else {
			w("    /\\ st' = [st EXCEPT ![i] = %q]", m.Resolver.Leaf(tr.Target))
		}
		if len(tr.Effects) == 0 {
			w("    /\\ UNCHANGED fx")
		} else {
			w("    /\\ fx' = [fx EXCEPT ![i] = Bump(@, %s)]", tlaSet(tr.Effects))
		}
		src := tlaSet(leavesUnder(t, tr.Source))
		if tr.Kind == "on" {
			w("Do_%s(i, c) ==", sfx)
			w("    /\\ Atomic")
			w("    /\\ st[i] \\in %s", src)
			w("    /\\ Apply_%s(i)", sfx)
			w("    /\\ UNCHANGED pend")
			w("    /\\ last' = StepOf(%q, i, c, \"do\")", tr.ID)
			w("Begin_%s(i, c) ==", sfx)
			w("    /\\ ~Atomic")
			w("    /\\ st[i] \\in %s", src)
			w("    /\\ ~InFlight(c)")
			w("    /\\ pend' = pend \\cup {Pending(c, i, %q)}", tr.ID)
			w("    /\\ UNCHANGED <<st, fx>>")
			w("    /\\ last' = StepOf(%q, i, c, \"begin\")", tr.ID)
			w("Commit_%s(i, c) ==", sfx)
			w("    /\\ Pending(c, i, %q) \\in pend", tr.ID)
			w("    /\\ Apply_%s(i)", sfx)
			w("    /\\ pend' = pend \\ {Pending(c, i, %q)}", tr.ID)
			w("    /\\ last' = StepOf(%q, i, c, \"commit\")", tr.ID)
			caller = append(caller, fmt.Sprintf("Do_%s(i, c)", sfx), fmt.Sprintf("Begin_%s(i, c)", sfx))
			commits = append(commits, fmt.Sprintf("Commit_%s(i, c)", sfx))
		} else {
			w("Do_%s(i) ==", sfx)
			w("    /\\ st[i] \\in %s", src)
			w("    /\\ Apply_%s(i)", sfx)
			w("    /\\ UNCHANGED pend")
			w("    /\\ last' = StepOf(%q, i, \"engine\", \"do\")", tr.ID)
			internal = append(internal, fmt.Sprintf("Do_%s(i)", sfx))
		}
		w("")
	}
	disj := func(name, quant string, items []string) {
		if len(items) == 0 {
			w("%s == FALSE", name)
			return
		}
		w("%s ==", name)
		if quant != "" {
			w("    %s :", quant)
		}
		for _, it := range items {
			w("        \\/ %s", it)
		}
	}
	disj("CallerStepOf(i)", "\\E c \\in Callers", caller)
	disj("CommitStepOf(i)", "\\E c \\in Callers", commits)
	disj("EngineStepOf(i)", "", internal)
	w("InternalOf(i) == EngineStepOf(i) \\/ CommitStepOf(i)")
	w("Internal == \\E i \\in Instances : InternalOf(i)")
	w("Terminated ==")
	w("    /\\ \\A i \\in Instances : st[i] \\in Final")
	w("    /\\ pend = {}")
	w("    /\\ UNCHANGED vars")
	w("Next == (\\E i \\in Instances : CallerStepOf(i)) \\/ Internal \\/ Terminated")
	w("Fairness == \\A i \\in Instances : WF_vars(InternalOf(i))")
	w("Spec == Init /\\ [][Next]_vars /\\ Fairness")
	w("====")
	return []byte(b.String())
}

// TLAPropsTemplate is the property module machinery formal new writes.
func TLAPropsTemplate(module, skeleton string) []byte {
	return []byte(fmt.Sprintf(`---- MODULE %s ----
\* Properties of %s. Hand-written; machinery never overwrites this file.
\* Invariants, temporal properties and reach predicates go here.
EXTENDS %s

\* Reach predicates: states the model must be able to reach, so a pass is not vacuous.
SomeFinal == \E i \in Instances : st[i] \in Final
====
`, module, skeleton, skeleton))
}
