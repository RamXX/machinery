// CheckMachines implements G3-machine.
func CheckMachines(design string) *Gate {
	g := NewGate("G3-machine  machines + oracle")
	g.startOrder()
	mdir := filepath.Join(design, "machines")
	files := sortedGlob(mdir, "*.machine.json")
	if len(files) == 0 {
		g.Errs = append(g.Errs, "no *.machine.json under "+mdir)
		return g
	}
	for _, path := range files {
		base := filepath.Base(path)
		m, err := ir.LoadMachineJSON(path)
		if err != nil {
			g.Errs = append(g.Errs, err.Error())
			continue
		}
		g.Count("machines")
		errs, warns, notes, counts := lint.LintMachine(m, base)
		g.Errs = append(g.Errs, errs...)
		g.Warns = append(g.Warns, warns...)
		g.Notes = append(g.Notes, notes...)
		g.Count("transitions", counts.Transitions)

		// S11: the structural lint and the TLA generator must admit the same
		// machine subset, so G3 runs the generator's own admissibility pass
		// (tla.Check, a thin wrapper over Generate: one validator, one
		// truth). A machine G3 passes is a machine verify-formal can
		// generate; the refusal carries the generator's own message so the
		// operator sees one vocabulary at either phase.
		if err := tla.Check(path); err != nil {
			g.Errs = append(g.Errs, base+": "+err.Error())
		} else {
			g.Count("tla-generable")
		}

		var exhaustive []string
		for _, s := range ir.WalkStates(m.AsObject().Get2("states"), "") {
			if s.Node != nil && s.Node.Kind == ir.KindObject {
				note := strings.TrimSpace(s.Node.AsObject().GetString("_exhaustive"))
				if note != "" {
					exhaustive = append(exhaustive, s.Name)
				}
			}
		}
		if len(exhaustive) > 0 {
			g.Count("states relying on unproven _exhaustive liveness", len(exhaustive))
			sort.Strings(exhaustive)
			g.Warns = append(g.Warns, base+": liveness for "+strings.Join(exhaustive, ", ")+
				" rests on an UNPROVEN _exhaustive claim (guards are erased in the TLA+ model, so TLC cannot check it); verify the guard set is provably total, or add an unguarded fallback branch so the liveness proof becomes sound")
		}

		opath := machineSibling(path, ".oracle.md")
		fresh := oracle.Render(m, path)
		if _, err := os.Stat(opath); err != nil {
			g.Errs = append(g.Errs, base+": no committed oracle ("+filepath.Base(opath)+"); run machinery oracle")
		} else if committed, err := os.ReadFile(opath); err != nil {
			g.Errs = append(g.Errs, base+": committed oracle is unreadable: "+err.Error())
		} else if g.recordStamp(string(committed)); version.Strip(string(committed)) != version.Strip(fresh) {
			// the stamp line is stripped from BOTH sides: a version-only skew
			// is surfaced by VersionSkewNote, never as DRIFT (P-F10)
			g.Drift = append(g.Drift, base+": committed oracle is stale (differs from a fresh generation); rerun machinery oracle")
		} else {
			g.Count("oracles fresh")
		}

		mpath := machineSibling(path, ".matrix.md")
		if _, err := os.Stat(mpath); err != nil {
			g.Warns = append(g.Warns, base+": no matrix file; named-unit contracts are unchecked (transitions are covered by the generated oracle)")
			continue
		}
		mtext := readFileOrErr(mpath, g)
		merrs, drift, nrows := lint.ReconcileMatrix(m, mtext, base)
		g.Errs = append(g.Errs, merrs...)
		g.Drift = append(g.Drift, drift...)
		g.Count("matrix rows reconciled", nrows)
		// S8: overlapping guards on one branch list argue about the same
		// invariant, so their order carries meaning the state must state.
		CheckBranchOrder(g, m, mtext, base)
		declared := lint.NamedUnitNames(mtext)
		guards, actions, actors := lint.MachineUnitNames(m)
		for _, pair := range []struct {
			kind  string
			names map[string]bool
		}{{"guard", guards}, {"action", actions}, {"actor", actors}} {
			var sorted []string
			for n := range pair.names {
				sorted = append(sorted, n)
			}
			sort.Strings(sorted)
			for _, name := range sorted {
				if declared[name] {
					g.Count("named units covered")
				} else {
					g.Drift = append(g.Drift, base+": "+pair.kind+" "+ir.Repr(name)+" has no named-unit contract row in "+filepath.Base(mpath))
				}
			}
		}
	}
	g.RequireNonzero("machines", "no machines parsed")
	g.RequireNonzero("transitions", "no transitions parsed")
	// S5 (v1 scope): dotted `Machine.state` references in annotation strings
	// and matrix prose must name real states, events, or units; the
	// narrative layer rots silently otherwise. Warnings only.
	CheckNameRot(g, design)
	return g
}

func sortedGlob(dir, pattern string) []string {
	entries, _ := os.ReadDir(dir)
	var out []string
	for _, e := range entries {
		if !e.IsDir() {
			matched, _ := filepath.Match(pattern, e.Name())
			if matched {
				out = append(out, filepath.Join(dir, e.Name()))
			}
		}
	}
	sort.Strings(out)
	return out
}

// machineSibling swaps a *.machine.json path's suffix for a sibling
// artifact's (".oracle.md", ".matrix.md").
func machineSibling(path, newExt string) string {
	return path[:len(path)-len(".machine.json")] + newExt
}

// --- traceability (Gx-trace) ---

func loadModelith(design string, g *Gate) *ir.Value {
	entries, _ := os.ReadDir(design)
	var paths []string
	for _, e := range entries {
		if strings.HasSuffix(e.Name(), ".modelith.yaml") {
			paths = append(paths, filepath.Join(design, e.Name()))
		}
	}
	if len(paths) == 0 {
		g.Errs = append(g.Errs, "no *.modelith.yaml in the design directory")
		return nil
	}
	if len(paths) > 1 {
		var names []string
		for _, p := range paths {
			names = append(names, filepath.Base(p))
		}
		sort.Strings(names)
		g.Errs = append(g.Errs, "multiple modelith models: "+strings.Join(names, ", "))
		return nil
	}
	data, err := os.ReadFile(paths[0])
	if err != nil {
		g.Errs = append(g.Errs, filepath.Base(paths[0])+": invalid YAML: "+err.Error())
		return nil
	}
	v, err := ir.LoadYAML(data)
	if err != nil {
		g.Errs = append(g.Errs, filepath.Base(paths[0])+": invalid YAML: "+err.Error())
		return nil
	}
	if v.AsObject() == nil {
		g.Errs = append(g.Errs, filepath.Base(paths[0])+": not a yaml mapping (empty file?)")
		return nil
	}
	return v
}

// CheckTraceability implements Gx-trace.
func CheckTraceability(design string) *Gate {
	g := NewGate("Gx-trace  cross-layer traceability")
	g.startOrder()
	dm := loadModelith(design, g)
	if dm == nil {
		return g
	}
	dmo := dm.AsObject()
	enums := map[string][]string{}
	if ev := dmo.Get2("enums"); ev != nil {
		for _, k := range ev.AsObject().Keys() {
			var vals []string
			for _, vv := range ev.AsObject().Get2(k).AsObject().Get2("values").AsArray() {
				vals = append(vals, vv.AsObject().GetString("name"))
			}
			enums[k] = vals
		}
	}
	entities := dmo.GetObject("entities")
	if entities.Len() == 0 {
		g.Errs = append(g.Errs, "modelith model declares no entities; an empty domain model is a failure, not a pass")
		return g
	}
	g.Count("entities", entities.Len())

	invIDs := map[string]bool{}
	for _, i := range objSlice(dmo.Get2("invariants")) {
		invIDs[i.AsObject().GetString("id")] = true
	}
	actionsByEntity := map[string]map[string]bool{}
	enumByEntity := map[string]string{}
	allActions := map[string]bool{}
	preservedIDs := map[string]bool{}
	for _, ename := range entities.Keys() {
		e := entities.Get2(ename).AsObject()
		acts := map[string]bool{}
		for _, a := range objSlice(e.Get2("actions")) {
			if a.Kind == ir.KindObject {
				acts[a.AsObject().GetString("name")] = true
				for _, pv := range listStrings(a.AsObject().Get2("preserves")) {
					preservedIDs[pv] = true
				}
			} else {
				acts[a.AsString()] = true
			}
		}
		actionsByEntity[ename] = acts
		for a := range acts {
			allActions[a] = true
		}
		for _, i := range objSlice(e.Get2("invariants")) {
			invIDs[i.AsObject().GetString("id")] = true
		}
		for _, a := range objSlice(e.Get2("attributes")) {
			ao := a.AsObject()
			if _, ok := enums[ao.GetString("type")]; ok {
				name := ao.GetString("name")
				if name == "status" || name == "stage" || name == "state" {
					enumByEntity[ename] = ao.GetString("type")
				}
			}
		}
	}

	mdir := filepath.Join(design, "machines")
	machineFiles := sortedGlob(mdir, "*.machine.json")
	if len(machineFiles) == 0 {
		g.Errs = append(g.Errs, "no machines under "+mdir+" to trace")
		return g
	}

	machineNames := map[string]bool{}
	claimed := map[string]bool{}
	for _, path := range machineFiles {
		base := filepath.Base(path)
		name := strings.TrimSuffix(base, ".machine.json")
		machineNames[name] = true
		m, err := ir.LoadMachineJSON(path)
		if err != nil {
			g.Errs = append(g.Errs, err.Error())
			continue
		}
		mo := m.AsObject()
		entity := mo.GetString("_lifecycle_of")
		if entity == "" {
			if _, ok := entities.Get(name); ok {
				entity = name
			}
		}
		role := mo.GetString("_role")
		if role == "operational" {
			entity = ""
		}
		if entity == "" && role != "operational" {
			g.Errs = append(g.Errs, base+": maps to no Modelith entity and is not declared operational (set _lifecycle_of: <Entity> or _role: operational)")
			continue
		}
		if role == "operational" {
			g.Count("operational machines")
			continue
		}
		if _, ok := entities.Get(entity); !ok {
			g.Errs = append(g.Errs, base+": _lifecycle_of "+ir.Repr(entity)+" is not a Modelith entity")
			continue
		}
		claimed[entity] = true
		enumName := enumByEntity[entity]
		if enumName == "" {
			g.Errs = append(g.Errs, base+": entity "+ir.Repr(entity)+" has no enum-typed lifecycle attribute")
			continue
		}
		vals := setOf(enums[enumName])
		var top []string
		for _, s := range ir.WalkStates(mo.Get2("states"), "") {
			if !strings.Contains(s.Path, ".") {
				top = append(top, s.Name)
			}
		}
		domainStates := map[string]bool{}
		var overlay []string
		for _, n := range top {
			if ir.IsUpperFirst(n) {
				domainStates[n] = true
			} else {
				overlay = append(overlay, n)
			}
		}
		var diff []string
		for s := range domainStates {
			if !vals[s] {
				diff = append(diff, s)
			}
		}
		sort.Strings(diff)
		for _, s := range diff {
			g.Errs = append(g.Errs, base+": domain state "+ir.Repr(s)+" is not a value of enum "+enumName+" (overlay states are lowerCamel by convention)")
		}
		var diff2 []string
		for v := range vals {
			if !domainStates[v] {
				diff2 = append(diff2, v)
			}
		}
		sort.Strings(diff2)
		for _, v := range diff2 {
			g.Errs = append(g.Errs, base+": enum "+enumName+" value "+ir.Repr(v)+" has no machine state; the lifecycle is incomplete")
		}
		if len(overlay) > 0 {
			g.Notes = append(g.Notes, name+": "+fmt.Sprintf("%d", len(overlay))+" operational-overlay states ("+strings.Join(overlay, ", ")+")")
		}
		events := map[string]bool{}
		for _, s := range ir.WalkStates(mo.Get2("states"), "") {
			if on := s.Node.AsObject().Get2("on"); on != nil {
				for _, ev := range on.AsObject().Keys() {
					events[ev] = true
				}
			}
		}
		var evSorted []string
		for ev := range events {
			evSorted = append(evSorted, ev)
		}
		sort.Strings(evSorted)
		for _, ev := range evSorted {
			if !actionsByEntity[entity][ev] {
				g.Errs = append(g.Errs, base+": event "+ir.Repr(ev)+" is not a Modelith action of "+entity)
			}
		}
		g.Count("lifecycle machines traced")
	}

	var enumEntities []string
	for ename := range enumByEntity {
		enumEntities = append(enumEntities, ename)
	}
	sort.Strings(enumEntities)
	for _, ename := range enumEntities {
		enumName := enumByEntity[ename]
		if !claimed[ename] {
			g.Errs = append(g.Errs, "entity "+ename+" has lifecycle enum "+enumName+" but no machine ("+ename+".machine.json); model the lifecycle or drop the enum")
		} else {
			g.Count("lifecycle entities with machines")
		}
	}

	// placement table
	persistedPlacements := checkPlacement(g, design, machineNames, entities)

	// residual-handler binding: opt-in on the mitigation table's "handled by"
	// column (see residual.go)
	checkResidualHandling(g, design, machineNames)

	// event-contract rows against the machines: the pack side of this check
	// runs only where a pack exists, so a design that carries one is left to
	// G5 rather than reported twice for one defect (see eventwiring.go)
	archText := readOrEmpty(filepath.Join(design, "ARCHITECTURE.md"))
	if !pack.HasPack(design) {
		checkEventWiring(g, design, archText)
	}
	// the consumer-READS completeness tier, armed by the design's own marker.
	// It runs on a packed design too: G5 reconciles boundary-event DIRECTION
	// from the generated events.md and has no notion of READS, so nothing
	// double-reports (see readscomplete.go)
	checkReadsComplete(g, design, archText)

	// invariants enforcement
	var cells, unitCells []string
	matrixFiles := globExt(mdir, ".matrix.md")
	for _, f := range matrixFiles {
		for _, tbl := range ir.ParseMdTables(readFileOrErr(f, g)) {
			mi := ir.FindCol(tbl.Header, "maps to")
			for _, r := range tbl.Rows {
				cells = append(cells, r...)
				if mi >= 0 && mi < len(r) {
					unitCells = append(unitCells, r[mi])
				}
			}
		}
	}
	build := filepath.Join(design, "BUILD.md")
	if _, err := os.Stat(build); err == nil {
		// every BUILD scan below runs fence-masked, matching Gb: a fenced
		// example "Mode:" line, heading, or table row is documentation, not a
		// declaration, and must neither satisfy the template checks nor credit
		// invariant enforcement in the traceability corpus
		buildText := maskFences(readFileOrErr(build, g))
		for _, tbl := range ir.ParseMdTables(buildText) {
			for _, r := range tbl.Rows {
				cells = append(cells, r...)
			}
		}
		// manifest mode shards contribute to the traceability corpus too
		for _, shard := range sortedGlobExt(filepath.Join(design, "BUILD"), ".md") {
			for _, tbl := range ir.ParseMdTables(maskFences(readFileOrErr(shard, g))) {
				for _, r := range tbl.Rows {
					cells = append(cells, r...)
				}
			}
			g.Count("build shards scanned")
		}
		// template conformance: deterministic structural requirements
		if modeRe.FindString(buildText) == "" {
			g.Errs = append(g.Errs, "BUILD.md declares no mode; the template requires a top 'Mode: full ...' or 'Mode: manifest ...' line")
		} else {
			g.Count("build mode declared")
		}
		if !headingContains(buildText, "toolchain") {
			g.Errs = append(g.Errs, "BUILD.md has no Toolchain heading; two implementing agents must not diverge on environment (pin language, libraries, test framework)")
		} else {
			g.Count("toolchain section present")
		}
		if persistedPlacements > 0 {
			if !headingContains(buildText, "state migration") {
				g.Errs = append(g.Errs, fmt.Sprintf("%d placement row(s) persist machine state but BUILD.md has no State migration heading (mapping table or drain rule for future state changes, or 'no persisted instances yet')", persistedPlacements))
			} else {
				g.Count("state-migration section present")
			}
		}
	} else {
		g.Warns = append(g.Warns, "BUILD.md not present; invariant enforcement is checked against the matrices only (fine before Phase 4)")
	}
	corpus := strings.Join(cells, "\n")
	unitCorpus := strings.Join(unitCells, "\n")
	if len(invIDs) == 0 {
		g.Errs = append(g.Errs, "the domain model declares no invariants; nothing constrains the design")
	}
	// the relational policy model is an enforcement artifact too: an
	// invariant compiled into Policy.als is solver-checked, which is
	// stronger than a prose reference (Gp-policy holds the annotation to
	// the domain model; here it only credits coverage)
	policyIDs := alloy.CarriedIDs(filepath.Join(design, "formal", alloy.AnnotationName))
	integrityIDs := alloy.CarriedIntegrityIDs(filepath.Join(design, "formal", alloy.IntegrityAnnotationName))
	isolationIDs := alloy.CarriedIsolationIDs(filepath.Join(design, "formal", alloy.IsolationAnnotationName))
	// an explicit waiver-with-reason (a layer residual, a checker coverage
	// residual, or the formal/waivers.yaml annex) is a recorded
	// disposition, not a gap; Gc-carrier and Gk own validating the waivers
	// themselves. A checker's coverage claim is an enforcement artifact
	// (Gk reconciles the evidence behind it).
	waivedIDs := map[string]bool{}
	for _, ann := range []string{alloy.AnnotationName, alloy.IntegrityAnnotationName, alloy.IsolationAnnotationName} {
		for iid := range alloy.ResidualIDs(filepath.Join(design, "formal", ann)) {
			waivedIDs[iid] = true
		}
	}
	for iid := range annexWaiverIDs(design) {
		waivedIDs[iid] = true
	}
	checkerIDs, checkerWaived := checkerClaims(design, invIDs)
	for iid := range checkerWaived {
		waivedIDs[iid] = true
	}
	var invSorted []string
	for iid := range invIDs {
		invSorted = append(invSorted, iid)
	}
	sort.Strings(invSorted)
	for _, iid := range invSorted {
		switch {
		case tokenIn(iid, unitCorpus):
			g.Count("invariants enforced")
			g.Count("invariants unit-backed (guard/action/actor)")
		case policyIDs[iid]:
			g.Count("invariants enforced")
			g.Count("invariants policy-checked (relational model)")
		case integrityIDs[iid]:
			g.Count("invariants enforced")
			g.Count("invariants integrity-checked (relational model)")
		case isolationIDs[iid]:
			g.Count("invariants enforced")
			g.Count("invariants isolation-checked (relational model)")
		case checkerIDs[iid]:
			g.Count("invariants enforced")
			g.Count("invariants checker-claimed (external checker)")
		case waivedIDs[iid]:
			g.Count("invariants waived with reason")
		case tokenIn(iid, corpus):
			// a prose table row is a claim, not a carrier: it satisfies a
			// reader, never a machine. Counted and warned as a residual so
			// hand-maintained rows cannot silently stand in for enforcement.
			// The two texts differ because the fixes differ: a
			// preserves-carried invariant must NOT be waived (Gc-carrier
			// would flag the waiver as stale); one carried by nothing must
			// be, or mapped.
			g.Count("invariants attested only (prose)")
			if preservedIDs[iid] {
				g.Warns = append(g.Warns, "invariant "+ir.Repr(iid)+" is carried by preserves but realized by no machine unit or relational layer; its enforcement rests on the prose tables and the tests they name (map it in a machine matrix or a relational layer)")
			} else {
				g.Warns = append(g.Warns, "invariant "+ir.Repr(iid)+" is attested only by prose table rows; map it to a machine unit or a relational layer, or waive it in formal/"+WaiverAnnexName)
			}
		default:
			g.Errs = append(g.Errs, "invariant "+ir.Repr(iid)+" is referenced by no matrix or BUILD.md table; it is enforced by nothing")
		}
	}

	// orphan references
	known := map[string]bool{}
	for iid := range invIDs {
		known[iid] = true
	}
	for a := range allActions {
		known[a] = true
	}
	for _, ename := range entities.Keys() {
		known[ename] = true
	}
	for _, vs := range enums {
		for _, v := range vs {
			known[v] = true
		}
	}
	for _, f := range matrixFiles {
		base := filepath.Base(f)
		for _, tbl := range ir.ParseMdTables(readOrEmpty(f)) { // read errors reported on the first pass above
			mi := ir.FindCol(tbl.Header, "maps to")
			if mi < 0 {
				continue
			}
			for _, r := range tbl.Rows {
				if mi >= len(r) {
					continue
				}
				for _, m := range kebabRe.FindAllStringSubmatch(r[mi], -1) {
					if !known[m[1]] {
						g.Drift = append(g.Drift, base+": maps-to references `"+m[1]+"`, which is not a declared invariant (typo or a stale reference)")
					}
				}
			}
		}
	}
	g.RequireNonzero("invariants enforced", "no invariant was traced to an enforcement artifact")
	return g
}

// checkPlacement holds the persistence-and-placement table in ARCHITECTURE.md
// and returns how many rows persist their state (the BUILD.md state-migration
// trigger). Two obligations, opposite directions:
//
//   - every ROW names a component in backticks that has a machine, or carries
//     a '(no machine: <reason>)' waiver;
//   - every ENTITY the domain model declares appears in some row's component
//     cell, or carries a '(not placed: <reason>)' waiver.
//
// The second is the completeness half. Unlike the dependency declaration,
// whose universe is open (a dependency nobody declared carries no obligation,
// so completeness there is attested), the entity list is CLOSED and
// enumerable from the model: an entity that simply never got a row is a hole
// no other gate can see, so it is checked here rather than trusted.
func checkPlacement(g *Gate, design string, machineNames map[string]bool, entities *ir.Object) int {
	persisted := 0
	arch := filepath.Join(design, "ARCHITECTURE.md")
	if _, err := os.Stat(arch); err != nil {
		return persisted
	}
	text := readFileOrErr(arch, g)
	placedEntities := map[string]bool{}
	waivedEntities := map[string]bool{}
	tableFound := false
	// EVERY header-matching table counts, as with the event, interface, and
	// mitigation tables: a design may split placement across sections (the
	// aggregates in one, the operational machines in another), and the
	// first-match locator silently excluded every later table's rows from both
	// obligations while the completeness half still demanded a row per entity.
	// Rows aggregate: the persisted count and the per-row findings accumulate,
	// and placement and waiver coverage are sets, so an entity placed in
	// either table is placed once.
	for _, tbl := range ir.ParseMdTables(text) {
		hl := strings.ToLower(strings.Join(tbl.Header, " "))
		if !strings.Contains(hl, "placement") || !strings.Contains(hl, "persistence") {
			continue
		}
		tableFound = true
		pi := ir.FindCol(tbl.Header, "persistence")
		mp := ir.FindCol(tbl.Header, "machine placement", "placement", "machine")
		for _, r := range tbl.Rows {
			if len(r) == 0 {
				continue
			}
			if pi >= 0 && pi < len(r) && isPersisted(r[pi]) {
				persisted++
			}
			// only a backticked token outside the annotation parentheses names
			// a component; a bare word is prose, and accepting it lets
			// de-backticked rows pass silently
			named := placementSubjects(r[0])
			if len(named) == 0 {
				g.Errs = append(g.Errs, "placement row names no component in backticks: "+ir.Repr(r[0]))
				continue
			}
			if m := notPlacedWaiverRe.FindStringSubmatch(r[0]); m != nil {
				// the row states the entity has no placement of its own (it
				// rides another aggregate's row, or is value-like): there is no
				// placement decision to record and so no machine to demand. An
				// empty reason is an unanswered design question, not a waiver;
				// the subjects still count as seen, so one defect never
				// cascades into a second finding against the same entity.
				for _, comp := range named {
					waivedEntities[comp] = true
				}
				if strings.TrimSpace(m[1]) == "" {
					g.Errs = append(g.Errs, "placement waiver for `"+named[0]+"` names no reason; write '(not placed: <reason>)'")
				}
				continue
			}
			for _, comp := range named {
				placedEntities[comp] = true
			}
			// the machine obligation binds the row's first component: the rest
			// are co-located subjects of the same placement decision
			comp := named[0]
			if machineNames[comp] {
				g.Count("placement rows with machines")
			} else if placementWaived(r, mp) {
				g.Count("placement rows waived")
			} else {
				g.Errs = append(g.Errs, "placement row component `"+comp+"` has no machine and no '(no machine: <reason>)' waiver in its component or machine-placement cell")
			}
		}
	}
	if !tableFound {
		g.Errs = append(g.Errs, fmt.Sprintf("ARCHITECTURE.md has no persistence-and-placement table (a header naming both placement and persistence); the model's %d entities can be traced to no placement decision", entities.Len()))
		return persisted
	}
	names := append([]string(nil), entities.Keys()...)
	sort.Strings(names)
	for _, ename := range names {
		switch {
		case placedEntities[ename]:
			g.Count("entities placed")
		case waivedEntities[ename]:
			g.Count("entities placement-waived")
		default:
			g.Errs = append(g.Errs, "entity `"+ename+"` appears in no persistence-and-placement row and carries no '(not placed: <reason>)' waiver; the placement table is incomplete")
		}
	}
	return persisted
}

// noMachineWaiverRe is the placement waiver token with its reason captured.
var noMachineWaiverRe = regexp.MustCompile(`\(no machine:\s*([^)]*)\)`)

// notPlacedWaiverRe is the placement-completeness waiver token with its reason
// captured: a declared entity that deliberately has no placement row of its
// own. Distinct from '(no machine: <reason>)', which waives the MACHINE of a
// component that is placed.
var notPlacedWaiverRe = regexp.MustCompile(`\(not placed:\s*([^)]*)\)`)

// parenAnnotationRe matches a parenthesized annotation in a placement
// component cell.
var parenAnnotationRe = regexp.MustCompile(`\([^)]*\)`)

// placementSubjects returns the components a placement row's first cell names:
// the backticked tokens OUTSIDE any parenthetical annotation. A name mentioned
// inside a waiver reason is prose about another row's component, never a
// placement of its own ("`Holding` (no machine: rows written with their
// `Portfolio`)" places Holding, not Portfolio).
func placementSubjects(cell string) []string {
	return backtickTokens(parenAnnotationRe.ReplaceAllString(cell, " "))
}

// placementWaived recognizes the '(no machine: <reason>)' waiver only in the
// cells that name what is waived: the component cell (the portfolio-engine
// shape) or the machine-placement cell (the checkout-split shape). The token
// buried anywhere else in the row is prose, and an empty reason is an
// unanswered design question, not a waiver (GATE-5).
func placementWaived(row []string, placementCol int) bool {
	cells := []string{row[0]}
	if placementCol > 0 && placementCol < len(row) {
		cells = append(cells, row[placementCol])
	}
	for _, cell := range cells {
		if m := noMachineWaiverRe.FindStringSubmatch(cell); len(m) > 1 && strings.TrimSpace(m[1]) != "" {
			return true
		}
	}
	return false
}

func backtickTokens(s string) []string {
	re := regexp.MustCompile("`([A-Za-z_][A-Za-z0-9_]*)`")
	var out []string
	for _, m := range re.FindAllStringSubmatch(s, -1) {
		out = append(out, m[1])
	}
	return out
}

func globExt(dir, ext string) []string {
	entries, _ := os.ReadDir(dir)
	var out []string
	for _, e := range entries {
		if !e.IsDir() && strings.HasSuffix(e.Name(), ext) {
			out = append(out, filepath.Join(dir, e.Name()))
		}
	}
	sort.Strings(out)
	return out
}
