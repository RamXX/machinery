func TestJSONReport(t *testing.T) {
	design, oldBin, newBin := fixture(t)
	code, out, _ := runTool(t, "-old", oldBin, "-new", newBin, "-design", design, "-json")
	if code != exitUnexplained {
		t.Fatalf("exit = %d, want 1", code)
	}
	var rep report
	if err := json.Unmarshal([]byte(out), &rep); err != nil {
		t.Fatalf("not JSON: %v\n%s", err, out)
	}
	if rep.Exit != 1 || rep.NewTally != (tally{Blocking: 2, Warnings: 1}) || rep.Unexplained != (tally{Blocking: 2, Warnings: 1}) {
		t.Fatalf("tallies = %+v / %+v / exit %d", rep.NewTally, rep.Unexplained, rep.Exit)
	}
	if rep.Old.Skew == nil || rep.Old.Skew.Running != "v0.1.0" || rep.New.Skew != nil {
		t.Fatalf("skew = %+v / %+v", rep.Old.Skew, rep.New.Skew)
	}
	wantVerdicts := []verdictChange{{"Gl-ledger", "absent", "fail"}, {"Gv-attest", "fail", "ok"}}
	if !reflect.DeepEqual(rep.Verdicts, wantVerdicts) {
		t.Fatalf("verdicts = %+v", rep.Verdicts)
	}
	var gates []string
	for _, g := range rep.NewByGate {
		gates = append(gates, fmt.Sprintf("%s:%d/%d/%d", g.Gate, g.Blocking, g.Warnings, g.Unexplained))
	}
	if want := []string{"Gx-trace:0/1/1", "Gl-ledger:2/0/2"}; !reflect.DeepEqual(gates, want) {
		t.Fatalf("by gate = %v, want %v", gates, want)
	}
}

func TestSameFlagsReachBothBinaries(t *testing.T) {
	dir := t.TempDir()
	design := filepath.Join(dir, "design")
	impl := filepath.Join(dir, "impl")
	writeFile(t, filepath.Join(design, "BUILD.md"), "x\n", 0o644)
	writeFile(t, filepath.Join(impl, "main.go"), "package main\n", 0o644)
	canned := "== Gu-surfaces  target surface ledger ==\n  ok\n\n0 blocking (ERROR/DRIFT) finding(s)\n"
	logs := filepath.Join(dir, "args")
	record := func(name string) string {
		return writeFake(t, dir, name, fake{version: "v1", canned: canned, before: `echo "$@" > '` + logs + "." + name + `'`})
	}
	oldBin, newBin := record("old"), record("new")
	code, out, stderr := runTool(t, "-old", oldBin, "-new", newBin, "-design", design, "-impl", impl, "-commit", "abc123", "-gates", "gu,gx")
	if code != exitOK {
		t.Fatalf("exit = %d\n%s%s", code, out, stderr)
	}
	oldArgs, _ := os.ReadFile(logs + ".old")
	newArgs, _ := os.ReadFile(logs + ".new")
	pattern := "check design --impl "
	if !strings.HasPrefix(string(oldArgs), pattern) || !strings.HasSuffix(strings.TrimSpace(string(oldArgs)), "/impl --commit abc123 --gate gu,gx") {
		t.Fatalf("old args = %q", oldArgs)
	}
	strip := func(b []byte) string { // the impl copy path differs per run
		f := strings.Fields(string(b))
		f[3] = "<impl>"
		return strings.Join(f, " ")
	}
	if strip(oldArgs) != strip(newArgs) {
		t.Fatalf("flags differ: %q vs %q", oldArgs, newArgs)
	}
	if !strings.Contains(out, "run      machinery check <design> --impl <impl> --commit abc123 --gate gu,gx") {
		t.Fatalf("report does not state the flags\n%s", out)
	}
}

