// TestRealBinaryOverAMutatedExampleCopy runs the machinery binary built from
// this tree on both sides; the candidate side is a wrapper that adds an
// em dash to its private copy, which the house-style gate reports.
func TestRealBinaryOverAMutatedExampleCopy(t *testing.T) {
	if testing.Short() {
		t.Skip("builds the machinery binary")
	}
	if runtime.GOOS == "windows" {
		t.Skip("the wrapper is a POSIX shell script")
	}
	dir := t.TempDir()
	real := filepath.Join(dir, "machinery")
	build := exec.CommandContext(t.Context(), "go", "build", "-o", real, "./cmd/machinery")
	build.Dir = filepath.Join("..", "..")
	if out, err := build.CombinedOutput(); err != nil {
		t.Fatalf("build machinery: %v\n%s", err, out)
	}
	design := filepath.Join(dir, "design")
	if err := copyTree(filepath.Join("..", "..", "examples", "fulfillment", "design"), design); err != nil {
		t.Fatal(err)
	}
	before, err := hashTree(design)
	if err != nil {
		t.Fatal(err)
	}
	wrapper := filepath.Join(dir, "candidate")
	script := "#!/bin/sh\nif [ \"$1\" = check ]; then printf 'A note \\342\\200\\224 with a dash.\\n' > \"$2/NOTES.md\"; fi\nexec '" + real + "' \"$@\"\n"
	if err := os.WriteFile(wrapper, []byte(script), 0o700); err != nil {
		t.Fatal(err)
	}

	code, out, stderr := runTool(t, "-old", real, "-new", wrapper, "-design", design)
	if code != exitUnexplained {
		t.Fatalf("exit = %d, want 1\n%s%s", code, out, stderr)
	}
	for _, want := range []string{
		"== new findings: 0 blocking, 1 warnings, 0 notes ==",
		"  Gl-ledger      warn  NOTES.md:1: em dash (U+2014); house style forbids it",
		"  Gl-ledger      ok -> warn",
		"note: the new binary wrote into its private copy of the tree (the original is unchanged): NOTES.md",
	} {
		if !strings.Contains(out, want) {
			t.Errorf("report lacks %q\n%s", want, out)
		}
	}

	allow := writeAllow(t, "gl warn /^NOTES\\.md:1: em dash/ the synthetic mutation adds exactly this line\n")
	code, out, stderr = runTool(t, "-old", real, "-new", wrapper, "-design", design, "-allow", allow)
	if code != exitOK {
		t.Fatalf("with allow: exit = %d, want 0\n%s%s", code, out, stderr)
	}

	after, err := hashTree(design)
	if err != nil {
		t.Fatal(err)
	}
	if d := diffManifests(before, after); len(d) > 0 {
		t.Fatalf("the example copy changed: %v", d)
	}
}
