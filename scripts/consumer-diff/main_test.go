type fake struct {
	version string
	canned  string
	exit    int
	before  string // shell run before the output is printed
	stderr  string
}

// writeFake writes a small shell script that behaves like `machinery check`
// with canned output.
func writeFake(t *testing.T, dir, name string, f fake) string {
	t.Helper()
	if runtime.GOOS == "windows" {
		t.Skip("fake binaries are POSIX shell scripts")
	}
	canned := filepath.Join(dir, name+".out")
	if err := os.WriteFile(canned, []byte(f.canned), 0o600); err != nil {
		t.Fatal(err)
	}
	script := fmt.Sprintf(`#!/bin/sh
if [ "$1" = "--version" ]; then echo "machinery version %s"; exit 0; fi
%s
sed "s#@DESIGN@#$(pwd)/$2#g" '%s'
printf '%%s' '%s' >&2
exit %d
`, f.version, f.before, canned, f.stderr, f.exit)
	path := filepath.Join(dir, name)
	if err := os.WriteFile(path, []byte(script), 0o700); err != nil {
		t.Fatal(err)
	}
	return path
}

// fixture makes a synthetic design tree and the two standard fakes.
func fixture(t *testing.T) (design, oldBin, newBin string) {
	t.Helper()
	dir := t.TempDir()
	design = filepath.Join(dir, "design")
	writeFile(t, filepath.Join(design, "BUILD.md"), "# Build\n", 0o644)
	writeFile(t, filepath.Join(design, "machines", "Order.matrix.md"), "| row |\n", 0o644)
	oldBin = writeFake(t, dir, "old", fake{version: "v0.1.0", canned: oldCanned, exit: 1})
	newBin = writeFake(t, dir, "new", fake{version: "v0.2.0", canned: newCanned, exit: 1})
	return design, oldBin, newBin
}

func writeAllow(t *testing.T, body string) string {
	t.Helper()
	path := filepath.Join(t.TempDir(), "allow.txt")
	if err := os.WriteFile(path, []byte(body), 0o600); err != nil {
		t.Fatal(err)
	}
	return path
}

func runTool(t *testing.T, args ...string) (int, string, string) {
	t.Helper()
	var out, errOut bytes.Buffer
	code := run(args, &out, &errOut)
	return code, out.String(), errOut.String()
}

func TestUnexplainedNewFindingsExitOne(t *testing.T) {
	design, oldBin, newBin := fixture(t)
	code, out, stderr := runTool(t, "-old", oldBin, "-new", newBin, "-design", design)
	if code != exitUnexplained {
		t.Fatalf("exit = %d, want 1\n%s%s", code, out, stderr)
	}
	for _, want := range []string{
		"consumer-diff: v0.1.0 -> v0.2.0 over " + design,
		"run      machinery check <design>",
		"1 blocking, 1 warnings, 2 notes; exit 1",
		"2 blocking, 2 warnings, 1 notes; exit 1",
		"stamps   old run: artifacts stamped by machinery v0.2.0, running v0.1.0",
		"stamps   new run: no version-stamp skew",
		"== new findings: 2 blocking, 1 warnings, 0 notes ==",
		"  Gx-trace       warn  Order.matrix.md:14: row 'pack': undeclared fact reference `parcel`",
		"  Gl-ledger      ERROR <root>/BUILD.md:3: unknown declaration group MACHINE-WRITTEN{...}",
		"  Gl-ledger      ERROR BUILD.md:9: solver finished in <duration> under machinery <version> at <tmp>",
		"== resolved findings: 1 blocking, 0 warnings, 1 notes ==",
		"  Gv-attest      DRIFT [stamp-skew] machines/Order.oracle.json is stale; regenerate with 'machinery oracle <root>/machines'",
		"  (run)          note  [stamp-skew] note: artifacts generated by machinery <version>, running <version>; regenerate on upgrade:",
		"  Gl-ledger      absent -> fail",
		"  Gv-attest      fail -> ok",
		"FAIL: 3 unexplained new finding(s): 2 blocking, 1 warnings",
	} {
		if !strings.Contains(out, want) {
			t.Errorf("report lacks %q\n%s", want, out)
		}
	}
	if strings.Contains(out, "Order.matrix.md:12") {
		t.Errorf("a finding present in both runs must not be reported\n%s", out)
	}
	if strings.Contains(out, "Gu-surfaces") {
		t.Errorf("a changed checked: count is not a finding\n%s", out)
	}
}

