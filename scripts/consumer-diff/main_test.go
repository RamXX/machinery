func TestUsageAndInputErrorsExitTwo(t *testing.T) {
	design, oldBin, newBin := fixture(t)
	notExec := filepath.Join(t.TempDir(), "plain")
	writeFile(t, notExec, "x", 0o644)
	cases := []struct {
		name string
		args []string
		want string
	}{
		{"missing flags", []string{"-old", oldBin}, "missing required -new, -design"},
		{"stray argument", []string{"-old", oldBin, "-new", newBin, "-design", design, "extra"}, "unexpected arguments: extra"},
		{"no design", []string{"-old", oldBin, "-new", newBin, "-design", filepath.Join(design, "nope")}, "does not exist"},
		{"design is a file", []string{"-old", oldBin, "-new", newBin, "-design", filepath.Join(design, "BUILD.md")}, "is not a directory"},
		{"no impl", []string{"-old", oldBin, "-new", newBin, "-design", design, "-impl", filepath.Join(design, "nope")}, "impl"},
		{"no binary", []string{"-old", filepath.Join(design, "nope"), "-new", newBin, "-design", design}, "-old: binary"},
		{"not executable", []string{"-old", oldBin, "-new", notExec, "-design", design}, "not an executable file"},
		{"bad allow file", []string{"-old", oldBin, "-new", newBin, "-design", design, "-allow", writeAllow(t, "gx warn /x/\n")}, "reason is mandatory"},
		{"bad flag", []string{"-bogus"}, "flag provided but not defined"},
	}
	for _, c := range cases {
		code, _, stderr := runTool(t, c.args...)
		if code != exitError || !strings.Contains(stderr, c.want) {
			t.Errorf("%s: exit = %d, stderr = %q; want 2 mentioning %q", c.name, code, stderr, c.want)
		}
	}
}

